import type { NoticeDetail } from '@/features/notices/types';

function daysAgo(n: number, hour = 11, minute = 30): string {
  const d = new Date();
  d.setDate(d.getDate() - n);
  d.setHours(hour, minute, 0, 0);
  return d.toISOString();
}

